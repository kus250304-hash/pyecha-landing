"""
동·구 페이지의 공통 문장(소개문, 공통 FAQ 답변, 마무리 문단)을 여러 벌로 두고 페이지마다 다른 조합을 고른다.

- 벌마다 뜻은 같아도 되지만 문장 구조·순서·어휘가 다르게 쓴다.
- 결과 약속 표현(보장·무조건·100%·1위·최저가)과 "최고가"·"1등"·"최대", 금액·시세 숫자는 쓰지 않는다.
- 첫 화면 핵심 문장(수출 비교 / 먼저 입금), 폼 제목(차량번호와 연락처), 폼 아래 비교 안내, 진행 순서의 입금·말소증 문자는
  템플릿에 고정 글자로 들어 있어 어느 벌을 골라도 모든 페이지에 나온다(2026-10-01). 여기 벌들은 그 문장과 어긋나지 않게 쓴다.
  소개의 hero 줄은 첫 화면 버튼 아래 작은 글씨, 마무리의 lead 줄은 아래쪽 폼 제목 밑에 들어간다.
- 조합은 (소개, FAQ, 마무리) 세 칸이고 칸마다 5벌이다. 같은 구 안의 동 페이지끼리는
  조합이 겹치지 않게 배정한다(구 하나에 125개까지). 구 페이지는 전체 구 목록 순서로 배정한다.
- 필수 문구: 소개의 sec 줄은 "실제 출장 방문이 가능한 지역"을 꼭 포함한다(check_pages.py 가 찾음).
"""
import hashlib
import re

N = 5  # 칸마다 벌 수


def josa(word: str, with_final: str, without_final: str) -> str:
    """앞 낱말 끝 글자의 받침에 맞춰 은/는, 이/가, 을/를 을 고른다. 끝의 괄호 설명은 빼고 본다(애오개(아현역) → 애오개를)."""
    word = re.sub(r"\s*\([^()]*\)$", "", word)
    ch = word[-1] if word else "가"
    if "가" <= ch <= "힣":
        return with_final if (ord(ch) - 0xAC00) % 28 else without_final
    return with_final if ch in "013678" else without_final


def _h(key: str) -> int:
    return int(hashlib.sha1(key.encode("utf-8")).hexdigest(), 16)


def assign_combos(slugs_by_group: dict[str, list[str]]) -> dict[str, tuple[int, int, int]]:
    """그룹(구)마다 슬러그를 정렬해 i 번째에 서로 다른 (소개, FAQ, 마무리) 조합을 준다.
    i → (i%5, i//5%5, i//25%5) 는 125개까지 겹치지 않고, 그룹마다 시작점을 달리해 구끼리도 섞이게 한다."""
    out = {}
    for group, slugs in slugs_by_group.items():
        h = _h(group)
        o1, o2, o3 = h % N, (h // N) % N, (h // (N * N)) % N
        for i, slug in enumerate(sorted(slugs)):
            a, b, c = i % N, (i // N) % N, (i // (N * N)) % N
            # 칸끼리 같은 번호가 줄지어 나오지 않게 FAQ·마무리 칸은 앞 칸 번호만큼 밀어 준다(여전히 겹치지 않음)
            out[slug] = ((a + o1) % N, (b + a + o2) % N, (c + b + o3) % N)
    return out


