def fill(text: str, **kw: str) -> str:
    """{dong}{은는} 처럼 이름 뒤 조사 자리를 받침에 맞게 채운다."""
    for key, word in kw.items():
        for pair, (a, b) in (("은는", ("은", "는")), ("이가", ("이", "가")), ("을를", ("을", "를"))):
            text = text.replace("{" + key + "}{" + pair + "}", word + josa(word, a, b))
        text = text.replace("{" + key + "}", word)
    return text


