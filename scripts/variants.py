def call_faqs(key: str, n: int) -> list[tuple[str, str]]:
    """실제 통화 FAQ 를 n 개 고른다. 첫 줄("얼마")은 늘 넣고, 나머지는 key(슬러그 등)마다 다른 출발점·간격으로 고른다."""
    rest = CALL_FAQ[1:]
    m = len(rest)
    h = _h("call:" + key)
    steps = [s for s in range(1, m) if math.gcd(s, m) == 1]
    start, step = h % m, steps[(h // m) % len(steps)]
    return [CALL_FAQ[0]] + [rest[(start + k * step) % m] for k in range(n - 1)]


