LEADING_COMMENT_RE = re.compile(r"<!DOCTYPE html>\s*<!--.*?-->", re.DOTALL)


def fill(template: str, region: dict) -> str:
    full_name = f"{region['sido']} {region['sigungu']} {region['dong']}".strip()
    full_name = re.sub(r"\s+", " ", full_name)
    page_title = f"{full_name} 폐차 비교매입 상담"

    values = {
        "REGION_SIDO": region["sido"],
        "REGION_SIGUNGU": region["sigungu"],
        "REGION_DONG": region["dong"],
        "REGION_FULL_NAME": full_name,
        "PAGE_TITLE": page_title,
        "META_DESCRIPTION": region["meta"],
        "SERVICE_INTRO": region["service_intro"],
        "PHONE_NUMBER_TEL": PHONE_TEL,
        "PHONE_NUMBER_DISPLAY": PHONE_DISPLAY,
        "LANDMARK_NAME": region["landmark_name"],
        "LANDMARK_DESCRIPTION": region["landmark_desc"],
        "PRIVACY_POLICY_URL": PRIVACY_URL,
    }

    for i, (name, rating, text) in enumerate(region["reviews"], start=1):
        values[f"REVIEW_{i}_NAME"] = name
        values[f"REVIEW_{i}_RATING"] = rating
        values[f"REVIEW_{i}_TEXT"] = text

    for i, (question, answer) in enumerate(region["faqs"], start=1):
        values[f"FAQ_{i}_QUESTION"] = question
        values[f"FAQ_{i}_ANSWER"] = answer

    def replace(match: "re.Match") -> str:
        key = match.group(1)
        if key not in values:
            raise KeyError(f"missing value for placeholder: {key}")
        return values[key]

    cleaned = LEADING_COMMENT_RE.sub("<!DOCTYPE html>", template, count=1)
    return re.sub(r"\{\{(\w+)\}\}", replace, cleaned)


def main() -> None:
    template = TEMPLATE_PATH.read_text(encoding="utf-8")
    OUTPUT_DIR.mkdir(exist_ok=True)

    for region in REGIONS:
        html = fill(template, region)
        out_path = OUTPUT_DIR / f"{region['slug']}.html"
        out_path.write_text(html, encoding="utf-8")
        print(f"생성 완료: {out_path.relative_to(ROOT)}")

    print(f"\n총 {len(REGIONS)}개 페이지 생성")

    sitemap_path = update_sitemap(ROOT, [region["slug"] for region in REGIONS])
    print(f"sitemap.xml 갱신 완료: {sitemap_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
